-- =============================================================================
-- 第 1 部分:序号表
-- 用途:所有大表都由序号表派生,避免逐行编写 INSERT。
-- 提示:递归 CTE 默认深度仅 1000,必须先放宽;若版本对递归 CTE 支持有限,
--       可改用"小表自乘"(见备选写法),速度更快。
-- =============================================================================
DROP TABLE IF EXISTS seq_numbers;
DROP TABLE IF EXISTS seq_small;

SET SESSION cte_max_recursion_depth = 2000;

CREATE TABLE seq_small (
  n INT UNSIGNED NOT NULL,
  PRIMARY KEY (n)
) ENGINE=InnoDB COMMENT='序号小表(1..1500),用于自乘生成大序号表';

INSERT INTO seq_small (n)
WITH RECURSIVE s(n) AS (
  SELECT 1 UNION ALL SELECT n + 1 FROM s WHERE n < 1500
)
SELECT n FROM s;

-- 备选写法(不依赖递归 CTE,兼容性更好、速度更快):
--   INSERT INTO seq_small (n) SELECT (a.n-1)*100 + b.n FROM
--     (SELECT 1 n UNION SELECT 2 UNION ... SELECT 10) a CROSS JOIN (...) b;

CREATE TABLE seq_numbers (
  n INT UNSIGNED NOT NULL,
  PRIMARY KEY (n)
) ENGINE=InnoDB COMMENT='序号表(1..2250000),所有大表的数据源';

INSERT INTO seq_numbers (n)
SELECT (a.n - 1) * 1500 + b.n
FROM seq_small a CROSS JOIN seq_small b;

-- 自检:应返回 2250000
SELECT COUNT(*) AS seq_total, MIN(n) AS seq_min, MAX(n) AS seq_max FROM seq_numbers;


