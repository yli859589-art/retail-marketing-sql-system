-- ---------- 2.3 券模板(40 行,按面额/门槛/有效期三要素规律生成) ----------
-- 约束要求:face_value > 0;min_amount >= face_value(跨列检查,BR-21);
--           valid_days > 0;status ∈ {启用,停用}
-- 设计:
--   面额      = 5 × (1 + (n-1) MOD 4)                 → 5 / 10 / 15 / 20
--   使用门槛  = 面额 × (2 或 3)                        → 始终远大于面额,满足 BR-21
--   有效天数  = 7 × (1 + ((n-1) DIV 8) MOD 5)          → 7 / 14 / 21 / 28 / 35
--   适用品类  = 每 5 个模板中有 4 个限定二级品类、1 个不限品类(NULL,即通用券)
--   状态      = 前 32 个启用、后 8 个停用(停用模板不发放任何券,可用于验证"停用模板无券")
INSERT INTO coupon_template
  (template_id, template_name, face_value, min_amount, valid_days, category_id, status, created_by, created_at)
SELECT s.n,
       CONCAT('券模板', LPAD(s.n, 3, '0'), '-', 5 * (1 + ((s.n - 1) MOD 4)), '元门槛',
              5 * (1 + ((s.n - 1) MOD 4)) * (2 + (((s.n - 1) DIV 4) MOD 2))),
       5 * (1 + ((s.n - 1) MOD 4)),
       5 * (1 + ((s.n - 1) MOD 4)) * (2 + (((s.n - 1) DIV 4) MOD 2)),
       7 * (1 + (((s.n - 1) DIV 8) MOD 5)),
       CASE WHEN (s.n - 1) MOD 5 = 0 THEN NULL
            ELSE 100 + ((s.n - 1) MOD 50) DIV 5 * 10 + ((s.n - 1) MOD 5) + 1 END,
       CASE WHEN s.n <= 32 THEN '启用' ELSE '停用' END,
       '营销运营组',
       '2023-06-01 00:00:00'
FROM seq_numbers s
WHERE s.n <= 40;


